public class Variables_reassign {
    public static void main(String[] args) {
        int marks = 60;
        System.out.println("My marks in 1st Subject is : " +marks);
        marks = 75;
        System.out.println("My marks improved when i write in second time of same subject, The marks i got in 2nd time : " +marks);
        marks = 90;
        System.out.println("My marks improved when i write in third time of same subject, The marks i got  : " + marks);
    }
}
